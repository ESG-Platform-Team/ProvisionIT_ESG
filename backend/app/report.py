"""
The PDF report. Same content as the screen, nothing simplified away.

Sequence diagram 5 as code: load the run, render band, confidence letter and
citation list, and carry the machine-interpretation statement on the first page.
The report is rendered from the stored run payload, so a PDF emailed in March can
be regenerated byte for byte from the run it names.

Branding follows the interface until Provision IT supplies a template; the colour
and type choices are the only things that would change.
"""

