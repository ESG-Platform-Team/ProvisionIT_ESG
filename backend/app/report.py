INK = colors.HexColor("#0E0F14")
MID = colors.HexColor("#4A4E5C")
MUTE = colors.HexColor("#8A8F9C")
LINE = colors.HexColor("#DCDEE4")
PAPER = colors.HexColor("#F4F5F7")
AMB = colors.HexColor("#F4BF3F")
AMB_SOFT = colors.HexColor("#FDF3D8")
DEEP = colors.HexColor("#8A6A12")

FONT_DIR = Path(__file__).parent / "fonts"
_FONTS_READY = False

STATUS_LABEL = {
    "DISCLOSED": "Evidenced",
    "NOT_DISCLOSED": "Not disclosed",
    "NOT_DISCLOSED_EXPLAINED": "Departs, explained",
    "NOT_APPLICABLE": "Not required",
    "EVIDENCE_GAP": "Not retrieved",
}
BAND_LABEL = {
    "LEADING": "Leading", "ESTABLISHED": "Established", "DEVELOPING": "Developing",
    "MINIMAL": "Minimal", "NOT_EVIDENCED": "Not evidenced",
    "INSUFFICIENT_EVIDENCE": "Not rated", "DEPARTS_EXPLAINED": "Departs, explained",
}
REQUEST_LABEL = {
    "SENT": "Awaiting response", "RESPONDED": "Responded",
    "DECLINED": "Declined", "NO_RESPONSE": "No response by due date",
}


def _fonts() -> tuple[str, str, str, str]:
    """Brand fonts if present, Helvetica otherwise. Returns body, bold, display,
    mono font names."""
    global _FONTS_READY
    files = {"Inter": "Inter-Regular.ttf", "Inter-SemiBold": "Inter-SemiBold.ttf",
             "Archivo": "Archivo-ExtraBold.ttf", "PlexMono": "IBMPlexMono-Regular.ttf"}
    if not _FONTS_READY:
        try:
            for name, file in files.items():
                pdfmetrics.registerFont(TTFont(name, str(FONT_DIR / file)))
            pdfmetrics.registerFontFamily("Inter", normal="Inter", bold="Inter-SemiBold",
                                          italic="Inter", boldItalic="Inter-SemiBold")
            _FONTS_READY = True
        except Exception:  # noqa: BLE001
            return "Helvetica", "Helvetica-Bold", "Helvetica-Bold", "Courier"
    return "Inter", "Inter-SemiBold", "Archivo", "PlexMono"


def _clean(text) -> str:
    """Escape for ReportLab markup and fold characters the Latin-1 font subsets
    cannot draw, so CO₂ prints as CO2 rather than as a black box."""
    if text is None:
        return ""
    text = str(text)
    out = []
    for ch in text:
        if ord(ch) < 0x250 or ch in "‘’“”–—•…€™−°":
            out.append(ch)
            continue
        folded = unicodedata.normalize("NFKD", ch)
        out.append("".join(c for c in folded if ord(c) < 0x250) or "?")
    return escape("".join(out))


def _styles():
    body, bold, display, mono = _fonts()

    def s(name, **kw):
        base = dict(fontName=body, fontSize=9, leading=13, textColor=INK, alignment=TA_LEFT)
        base.update(kw)
        return ParagraphStyle(name, **base)

    return {
        "kicker": s("kicker", fontName=mono, fontSize=7.5, leading=10, textColor=MUTE),
        "kickerAmb": s("kickerAmb", fontName=mono, fontSize=7.5, leading=10, textColor=DEEP),
        "title": s("title", fontName=display, fontSize=26, leading=28, textColor=INK),
        "h1": s("h1", fontName=display, fontSize=17, leading=20, spaceBefore=4, spaceAfter=6),
        "h2": s("h2", fontName=bold, fontSize=10.5, leading=14, spaceBefore=10, spaceAfter=4),
        "body": s("body"),
        "muted": s("muted", textColor=MID, fontSize=8.5, leading=12),
        "small": s("small", fontSize=7.8, leading=10.5, textColor=MID),
        "quote": s("quote", fontSize=8.2, leading=11.5, textColor=INK, leftIndent=6),
        "mono": s("mono", fontName=mono, fontSize=7.5, leading=10, textColor=MID),
        "monoInk": s("monoInk", fontName=mono, fontSize=8, leading=10.5, textColor=INK),
        "cell": s("cell", fontSize=8, leading=10.5),
        "cellBold": s("cellBold", fontName=bold, fontSize=8, leading=10.5),
        "figure": s("figure", fontName=display, fontSize=22, leading=24, textColor=INK),
        "band": s("band", fontName=display, fontSize=12, leading=14, textColor=INK),
        "notice": s("notice", fontSize=8.8, leading=12.8, textColor=INK),
    }


def render(run: dict) -> bytes:
    """Render a completed run payload to PDF bytes."""
    st = _styles()
    body, bold, display, mono = _fonts()
    buf = io.BytesIO()
    company = run["company"]
    generated = datetime.datetime.now(datetime.timezone.utc).strftime("%d %b %Y %H:%M UTC")

    def on_page(canvas, doc):
        canvas.saveState()
        w, h = A4
        canvas.setFillColor(AMB)
        canvas.rect(0, h - 4, w, 4, stroke=0, fill=1)
        canvas.setFont(mono, 6.8)
        canvas.setFillColor(MUTE)
        canvas.drawString(18 * mm, 10 * mm,
                          f"PROVISION IT · MACHINE-FORMED ASSESSMENT · {run['runId']}")
        canvas.drawRightString(w - 18 * mm, 10 * mm,
                               f"{company['asxCode']} · generated {generated} · page {doc.page}")
        canvas.restoreState()

    doc = SimpleDocTemplate(
        buf, pagesize=A4, leftMargin=18 * mm, rightMargin=18 * mm,
        topMargin=16 * mm, bottomMargin=18 * mm,
        title=f"{company['name']} ESG assessment",
        author="Provision IT ESG Platform", subject="ESG disclosure assessment",
    )
    story: list = []
    story += _cover(run, st)
    for pillar in run.get("pillars") or [_legacy_pillar(run)]:
        story.append(PageBreak())
        story += _pillar(pillar, st)
    if run.get("disclosureRequests"):
        story.append(CondPageBreak(60 * mm))
        story += _requests(run["disclosureRequests"], st)
    story.append(PageBreak())
    story += _sources(run.get("sourceLog", []), st)
    story += _method(st)
    doc.build(story, onFirstPage=on_page, onLaterPages=on_page)
    return buf.getvalue()


def _legacy_pillar(run: dict) -> dict:
    return {"pillar": "GOVERNANCE", "label": "Governance", "matrixVersion": run.get("matrixVersion"),
            "frameworkEdition": run.get("frameworkEdition"),
            "frameworkName": "ASX Corporate Governance Council Principles and Recommendations",
            "unitName": "Principle", "draft": False,
            "result": run["result"], "principles": run["principles"]}


def _cover(run: dict, st: dict) -> list:
    body, bold, display, mono = _fonts()
    c = run["company"]
    date = (run.get("completedAt") or "")[:10]
    brand = Table([[Paragraph("<font color='#FFFFFF'>*</font>", ParagraphStyle(
        "star", fontName=display, fontSize=26, leading=26, alignment=1)),
        Paragraph("Provision IT", ParagraphStyle("brand", fontName=display, fontSize=13,
                                                 leading=16, textColor=INK))]],
        colWidths=[12 * mm, 60 * mm], rowHeights=[13 * mm])
    brand.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (0, 0), AMB), ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("LEFTPADDING", (1, 0), (1, 0), 8),
    ]))

    out = [brand, Spacer(1, 16 * mm),
           Paragraph("ESG DISCLOSURE ASSESSMENT · FREE PUBLIC SOURCES", st["kickerAmb"]),
           Spacer(1, 4),
           Paragraph(_clean(c["name"]).upper(), st["title"]),
           Spacer(1, 6),
           Paragraph(_clean(f"ASX: {c['asxCode']}  /  {c.get('sector', '')}  /  "
                            f"{c.get('tier', '')}  /  assessed {date}").upper(), st["kicker"]),
           Spacer(1, 12 * mm)]

    rows = [[Paragraph(h, st["kicker"]) for h in
             ["PILLAR", "BAND", "CONFIDENCE", "TRANSPARENCY", "PRACTICE", "MATRIX"]]]
    for p in run.get("pillars") or [_legacy_pillar(run)]:
        r = p["result"]
        t = r["transparencyScore"]["value"]
        pr = r["practiceScore"]["value"]
        rows.append([
            Paragraph(_clean(p["label"]), st["cellBold"]),
            Paragraph(_clean(BAND_LABEL.get(r["band"], r["band"])).upper(), st["band"]),
            Paragraph(_clean(r["confidence"]), st["monoInk"]),
            Paragraph("—" if t is None else f"{t * 100:.0f}%", st["monoInk"]),
            Paragraph("—" if pr is None else f"{pr:.1f} / 4", st["monoInk"]),
            Paragraph(_clean(p["matrixVersion"]) + (" · draft" if p.get("draft") else ""),
                      st["mono"]),
        ])
    summary = Table(rows, colWidths=[30 * mm, 42 * mm, 22 * mm, 26 * mm, 22 * mm, 32 * mm])
    summary.setStyle(TableStyle([
        ("LINEBELOW", (0, 0), (-1, 0), 0.8, INK),
        ("LINEBELOW", (0, 1), (-1, -1), 0.4, LINE),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("TOPPADDING", (0, 1), (-1, -1), 7), ("BOTTOMPADDING", (0, 1), (-1, -1), 7),
    ]))
    out += [summary, Spacer(1, 10 * mm)]

    interp = run.get("interpretation") or {}
    notice = [Paragraph("MACHINE INTERPRETATION", st["kickerAmb"]), Spacer(1, 3),
              Paragraph(_clean(interp.get("statement", "")), st["notice"])]
    if interp.get("note"):
        notice += [Spacer(1, 4), Paragraph(_clean(interp["note"]), st["muted"])]
    box = Table([[notice]], colWidths=[174 * mm])
    box.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), AMB_SOFT),
        ("LINEBEFORE", (0, 0), (0, -1), 3, AMB),
        ("LEFTPADDING", (0, 0), (-1, -1), 12), ("RIGHTPADDING", (0, 0), (-1, -1), 12),
        ("TOPPADDING", (0, 0), (-1, -1), 10), ("BOTTOMPADDING", (0, 0), (-1, -1), 10),
    ]))
    out += [box, Spacer(1, 8 * mm),
            Paragraph("HOW TO READ THIS REPORT", st["kicker"]), Spacer(1, 3),
            Paragraph(
                "Transparency and practice are reported separately and never averaged. "
                "Transparency is the share of criteria where the company published something "
                "we could locate and cite. Practice is the mean maturity, 0 to 4, of what those "
                "disclosures describe. The confidence letter grades the sources, A for audited "
                "primary documents through E for none, and never changes a band. A band of "
                "Not rated means coverage was too thin to defend one; declining is a result, "
                "not a failure. Criteria notation such as 3B pairs maturity with the grade of "
                "the source that evidenced it.", st["muted"])]
    return out


def _pillar(p: dict, st: dict) -> list:
    r = p["result"]
    counts = r.get("counts", {})
    out = [Paragraph(_clean(f"{p['label']} pillar · {p['frameworkName']}").upper(), st["kicker"]),
           Spacer(1, 2),
           Paragraph(_clean(f"{p['label']}: {BAND_LABEL.get(r['band'], r['band'])} "
                            f"· confidence {r['confidence']}").upper(), st["h1"])]
    if p.get("draft"):
        out.append(Paragraph(
            _clean(f"Matrix {p['matrixVersion']} is a draft under review. Treat this pillar's "
                   "criteria and bands as provisional."), st["kickerAmb"]))
    if r.get("declineReason"):
        out += [Spacer(1, 4), Paragraph(_clean(r["declineReason"]), st["body"])]
    t = r["transparencyScore"]["value"]
    pr = r["practiceScore"]["value"]
    figures = [
        ["TRANSPARENCY", "—" if t is None else f"{t * 100:.0f}%"],
        ["PRACTICE", "—" if pr is None else f"{pr:.1f} / 4"],
        ["CRITERIA IN SCOPE", str(counts.get("criteriaInScope", 0))],
        ["EVIDENCED", str(counts.get("findingsEvidenced", 0))],
        ["EVIDENCE GAPS", str(counts.get("evidenceGaps", 0))],
        ["SOURCES", f"{counts.get('sourcesRetrieved', 0)}/{counts.get('sourcesAttempted', 0)}"],
    ]
    fig = Table([[Paragraph(v, st["figure"] if i < 2 else st["h1"]) for i, (_, v) in enumerate(figures)],
                 [Paragraph(k, st["kicker"]) for k, _ in figures]],
                colWidths=[30 * mm, 40 * mm, 26 * mm, 26 * mm, 26 * mm, 26 * mm])
    fig.setStyle(TableStyle([
        ("LINEABOVE", (0, 0), (-1, 0), 0.8, INK), ("TOPPADDING", (0, 0), (-1, 0), 8),
        ("VALIGN", (0, 0), (-1, -1), "BOTTOM"),
    ]))
    out += [Spacer(1, 6), fig, Spacer(1, 6)]

    for principle in p["principles"]:
        head = Paragraph(_clean(
            f"{p['unitName']} {principle['number']:02d} · {principle['title']} · "
            f"{BAND_LABEL.get(principle['band'], principle['band'])}"), st["h2"])
        rows = []
        for row in principle["criteria"]:
            cell = [Paragraph(_clean(row["question"]), st["cell"])]
            if row.get("rationale"):
                cell.append(Paragraph(_clean(row["rationale"]), st["small"]))
            for ev in row.get("evidence", []):
                prov = " · provided on request" if ev.get("provenance") == "PROVIDED_ON_REQUEST" else ""
                cell.append(Paragraph("“" + _clean(ev["excerpt"]) + "”", st["quote"]))
                cell.append(Paragraph(_clean(
                    f"{ev.get('sourceGrade') or '?'} · {ev['locator']}{prov}"), st["mono"]))
            if row.get("disclosureRequest"):
                cell.append(Paragraph(_clean(row["disclosureRequest"]["note"]), st["kickerAmb"]))
            rows.append([
                Paragraph(_clean(row["criterionCode"]), st["monoInk"]),
                cell,
                Paragraph(_clean(STATUS_LABEL.get(row["status"], row["status"])).upper(),
                          st["kicker"] if row["status"] != "DISCLOSED" else st["monoInk"]),
                Paragraph(_clean(row.get("notation") or "—"), st["monoInk"]),
            ])
        table = Table(rows, colWidths=[14 * mm, 116 * mm, 28 * mm, 16 * mm], repeatRows=0)
        table.setStyle(TableStyle([
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("LINEBELOW", (0, 0), (-1, -1), 0.4, LINE),
            ("TOPPADDING", (0, 0), (-1, -1), 5), ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
            ("LEFTPADDING", (0, 0), (0, -1), 0),
        ]))
        out += [CondPageBreak(40 * mm), head, table]
    return out


def _requests(requests: list[dict], st: dict) -> list:
    out = [Spacer(1, 6), Paragraph("DISCLOSURE REQUESTS", st["h1"]),
           Paragraph("Information requested directly from the company where public sources "
                     "were silent or unreachable. Anything supplied is graded as provided on "
                     "request. A request with no response by its due date is recorded here, "
                     "and the criteria it covered remain as reported above: a gap stays "
                     "insufficient information and is never scored as zero.", st["muted"]),
           Spacer(1, 4)]
    rows = [[Paragraph(h, st["kicker"]) for h in ["REQUEST", "SENT", "DUE", "STATUS", "ITEMS"]]]
    for r in requests:
        rows.append([
            Paragraph(_clean(r["requestId"]), st["mono"]),
            Paragraph(_clean((r.get("sentAt") or "")[:10]), st["mono"]),
            Paragraph(_clean((r.get("dueAt") or "")[:10]), st["mono"]),
            Paragraph(_clean(REQUEST_LABEL.get(r["status"], r["status"])
                             + ("" if r.get("delivered") or r["status"] != "SENT"
                                else " (saved, not emailed)")), st["cellBold"]),
            Paragraph(_clean(", ".join(r.get("criteria", []))), st["mono"]),
        ])
    t = Table(rows, colWidths=[40 * mm, 22 * mm, 22 * mm, 36 * mm, 54 * mm])
    t.setStyle(TableStyle([("LINEBELOW", (0, 0), (-1, 0), 0.8, INK),
                           ("LINEBELOW", (0, 1), (-1, -1), 0.4, LINE),
                           ("VALIGN", (0, 0), (-1, -1), "TOP")]))
    return out + [t]


def _sources(log: list[dict], st: dict) -> list:
    out = [Paragraph("SOURCE LOG", st["h1"]),
           Paragraph("Every document the platform reached for and what came back, including "
                     "failures. A document that could not be retrieved is recorded as an outcome "
                     "rather than folded into a lower score.", st["muted"]), Spacer(1, 4)]
    rows = [[Paragraph(h, st["kicker"]) for h in ["DOCUMENT", "OUTCOME", "GRADE", "READ AS", "LOCATION"]]]
    for d in log:
        prov = " (provided on request)" if d.get("provenance") == "PROVIDED_ON_REQUEST" else ""
        rows.append([
            Paragraph(_clean(d["title"] + prov), st["cell"]),
            Paragraph(_clean(d["outcome"]), st["mono"]),
            Paragraph(_clean(d.get("sourceGrade") or "—"), st["monoInk"]),
            Paragraph(_clean(d.get("extractionMethod") or "—"), st["mono"]),
            Paragraph(_clean(d.get("url") or d.get("location") or ""), st["mono"]),
        ])
    t = Table(rows, colWidths=[52 * mm, 24 * mm, 14 * mm, 18 * mm, 66 * mm])
    t.setStyle(TableStyle([("LINEBELOW", (0, 0), (-1, 0), 0.8, INK),
                           ("LINEBELOW", (0, 1), (-1, -1), 0.4, LINE),
                           ("VALIGN", (0, 0), (-1, -1), "TOP")]))
    return out + [t]


def _method(st: dict) -> list:
    items = [
        ("Evidenced", "The company published something that addresses the criterion; maturity 1 to 4 describes how far the practice goes."),
        ("Departs, explained", "The company says it does not do this and gives a reason. Counts toward transparency, never lowers practice."),
        ("Not disclosed", "Public sources were reached and are silent on the criterion. A statement about the company."),
        ("Not retrieved", "No source that could answer the criterion was reached. A statement about our coverage, not the company."),
        ("Not required", "The criterion does not apply to this kind of entity."),
    ]
    out = [Spacer(1, 10 * mm), Paragraph("METHOD NOTES", st["h1"])]
    for k, v in items:
        out.append(Paragraph(f"<b>{_clean(k)}.</b> {_clean(v)}", st["muted"]))
        out.append(Spacer(1, 3))
    out.append(Spacer(1, 4))
    out.append(Paragraph(
        "Bands apply fixed thresholds to mean practice maturity: Leading 3.4, Established 2.2, "
        "Developing 1.4, Minimal 0.5. Below 55% coverage of in-scope criteria no band is issued. "
        "These thresholds are working values pending validation against hand-scored companies.",
        st["muted"]))
    return out
